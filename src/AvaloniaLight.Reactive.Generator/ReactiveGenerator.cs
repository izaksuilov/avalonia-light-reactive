using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace AvaloniaLight.Reactive.Generator
{
    /// <summary>
    /// Generates implementations for partial properties marked with the <c>[Reactive]</c> attribute.
    /// For a property <c>public partial T Name { get; set; }</c> it emits the implementation
    /// <c>get =&gt; field; set =&gt; RaiseAndSetIfChanged(ref field, value);</c>, so there is no need to
    /// declare a backing field or write trivial setters. The <c>RaiseAndSetIfChanged</c> method comes from the base class.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class ReactiveGenerator : IIncrementalGenerator
    {
        private const string AttributeMetadataName = "AvaloniaLight.Reactive.ReactiveAttribute";

        /// <summary>
        /// Source text of the attribute itself. Added to every assembly that references the generator.
        /// The EmbeddedAttribute marker hides the attribute from other assemblies even with InternalsVisibleTo:
        /// otherwise an assembly that sees the internal types of a neighbor would see two identical attributes (CS0436).
        /// </summary>
        private const string AttributeSource = """
            // <auto-generated/>
            #nullable enable
            namespace AvaloniaLight.Reactive
            {
                /// <summary>
                /// Marks a partial property for generation of the backing field and change notifications.
                /// The generator emits the implementation: get => field; set => RaiseAndSetIfChanged(ref field, value).
                /// </summary>
                [global::Microsoft.CodeAnalysis.EmbeddedAttribute]
                [global::System.AttributeUsage(global::System.AttributeTargets.Property, AllowMultiple = false, Inherited = false)]
                internal sealed class ReactiveAttribute : global::System.Attribute
                {
                }
            }
            """;

        /// <summary>Type display format: fully qualified, with special names and nullable annotations.</summary>
        private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
            .WithMiscellaneousOptions(
                SymbolDisplayMiscellaneousOptions.UseSpecialTypes
                | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

        /// <inheritdoc/>
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(ctx =>
            {
                // Compiler-provided EmbeddedAttribute definition: one per assembly, even if several generators request it.
                ctx.AddEmbeddedAttributeDefinition();
                ctx.AddSource("ReactiveAttribute.g.cs", SourceText.From(AttributeSource, Encoding.UTF8));
            });

            var sources = context.SyntaxProvider.ForAttributeWithMetadataName(
                    AttributeMetadataName,
                    predicate: static (node, _) =>
                        node is PropertyDeclarationSyntax property
                        && property.Modifiers.Any(SyntaxKind.PartialKeyword),
                    transform: static (ctx, _) => Build(ctx))
                .Where(static source => source is not null);

            context.RegisterSourceOutput(sources, static (spc, source) =>
                spc.AddSource(source!.Value.HintName, SourceText.From(source.Value.Text, Encoding.UTF8)));
        }

        /// <summary>
        /// Builds the final text of the partial property implementation. The model is a pair of strings
        /// (file name + text), so the step is cached by value.
        /// </summary>
        private static GeneratedSource? Build(GeneratorAttributeSyntaxContext context)
        {
            if (context.TargetSymbol is not IPropertySymbol property
                || context.TargetNode is not PropertyDeclarationSyntax { AccessorList: { } accessors } declaration)
                return null;

            // Static properties and indexers are not supported: RaiseAndSetIfChanged is an instance method.
            if (property.IsStatic || property.IsIndexer || property.SetMethod is null)
                return null;

            INamedTypeSymbol? containingType = property.ContainingType;
            if (containingType is null)
                return null;

            // Chain of nested types, from outermost to innermost.
            var typeChain = new List<INamedTypeSymbol>();
            for (INamedTypeSymbol? type = containingType; type is not null; type = type.ContainingType)
                typeChain.Insert(0, type);

            string? ns = property.ContainingNamespace is { IsGlobalNamespace: false } namespaceSymbol
                ? namespaceSymbol.ToDisplayString()
                : null;

            var builder = new StringBuilder();
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("#nullable enable");
            builder.AppendLine("#pragma warning disable CS8618 // non-nullable field may be uninitialized");
            builder.AppendLine("#pragma warning disable CS9264 // field value may be null in the getter");

            int indent = 0;
            bool hasNamespace = ns is not null;
            if (hasNamespace)
            {
                builder.Append("namespace ").Append(ns).AppendLine();
                builder.AppendLine("{");
                indent++;
            }

            foreach (INamedTypeSymbol type in typeChain)
            {
                AppendIndent(builder, indent);
                builder.Append("partial ").Append(GetTypeKeyword(type)).Append(' ').Append(GetTypeNameWithParameters(type)).AppendLine();
                AppendIndent(builder, indent);
                builder.AppendLine("{");
                indent++;
            }

            // Property and accessor modifiers are repeated from the declaration as written: the two parts
            // of a partial property must match literally. Default accessibility and explicit private
            // are treated as different by the compiler (CS8799); required and new must also be repeated (CS9257, CS8800).
            AppendIndent(builder, indent);
            AppendModifiers(builder, declaration.Modifiers)
                   .Append(property.Type.ToDisplayString(TypeFormat))
                   .Append(' ')
                   .Append(property.Name)
                   .AppendLine();
            AppendIndent(builder, indent);
            builder.AppendLine("{");

            foreach (AccessorDeclarationSyntax accessor in accessors.Accessors)
            {
                AppendIndent(builder, indent + 1);
                AppendModifiers(builder, accessor.Modifiers);
                if (accessor.IsKind(SyntaxKind.GetAccessorDeclaration))
                    builder.AppendLine("get => field;");
                else
                    builder.Append(accessor.Keyword.Text).AppendLine(" => RaiseAndSetIfChanged(ref field, value);");
            }

            AppendIndent(builder, indent);
            builder.AppendLine("}");

            for (int i = typeChain.Count - 1; i >= 0; i--)
            {
                indent--;
                AppendIndent(builder, indent);
                builder.AppendLine("}");
            }

            if (hasNamespace)
                builder.AppendLine("}");

            return new GeneratedSource(BuildHintName(ns, typeChain, property.Name), builder.ToString());
        }

        private static void AppendIndent(StringBuilder builder, int indent)
            => builder.Append(' ', indent * 4);

        private static StringBuilder AppendModifiers(StringBuilder builder, SyntaxTokenList modifiers)
        {
            foreach (SyntaxToken modifier in modifiers)
                builder.Append(modifier.Text).Append(' ');

            return builder;
        }

        /// <summary>Generated file name. Unique within the compilation by type path and property name.</summary>
        private static string BuildHintName(string? ns, List<INamedTypeSymbol> typeChain, string propertyName)
        {
            var builder = new StringBuilder();
            if (ns is not null)
                builder.Append(ns).Append('.');

            foreach (INamedTypeSymbol type in typeChain)
                builder.Append(type.Name).Append('`').Append(type.Arity).Append('.');

            builder.Append(propertyName);
            uint hash = Fnv1a(builder.ToString());

            for (int i = 0; i < builder.Length; i++)
            {
                if (!char.IsLetterOrDigit(builder[i]))
                    builder[i] = '_';
            }

            // The readable part is not unique: Roslyn compares file names case-insensitively (Id and ID),
            // and replacing separators merges A.B and A_B. A name collision breaks the whole generator output,
            // so a hash of the original path is appended. string.GetHashCode is unsuitable: it differs in every process.
            builder.Append('_').Append(hash.ToString("x8")).Append(".g.cs");
            return builder.ToString();
        }

        /// <summary>FNV-1a hash: stable across compiler runs.</summary>
        private static uint Fnv1a(string text)
        {
            uint hash = 2166136261;
            foreach (char c in text)
            {
                hash ^= c;
                hash *= 16777619;
            }

            return hash;
        }

        private static string GetTypeKeyword(INamedTypeSymbol type)
        {
            if (type.IsRecord)
                return type.TypeKind == TypeKind.Struct ? "record struct" : "record";

            return type.TypeKind switch
            {
                TypeKind.Struct => "struct",
                TypeKind.Interface => "interface",
                _ => "class",
            };
        }

        private static string GetTypeNameWithParameters(INamedTypeSymbol type)
        {
            if (type.TypeParameters.Length == 0)
                return type.Name;

            return type.Name + "<" + string.Join(", ", type.TypeParameters.Select(parameter => parameter.Name)) + ">";
        }

        private readonly record struct GeneratedSource(string HintName, string Text);
    }
}
